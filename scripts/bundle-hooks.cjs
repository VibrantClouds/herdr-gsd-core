#!/usr/bin/env node
/**
 * Inline each compiled adapter entry point into a standalone single-file bundle
 * (spec §12.5: "single-file bundles, no imports beyond Node builtins", enforced
 * by `scripts/verify-m2.cjs`).
 *
 * How it works: dependency modules reached through relative `require("./x")`
 * are wrapped in a tiny CommonJS registry; the ENTRY module's code is emitted
 * verbatim at top level so `module`, `exports`, `require.main === module` and
 * `__dirname` all keep their real meaning in the shipped file. `node:*` builtin
 * requires are left untouched.
 *
 * Re-runnable: when a bundle would overwrite its own entry, the raw tsc output
 * is preserved as `.<name>.entry.js` first, so bundling is idempotent and a
 * dependency-only change still produces a fresh bundle.
 *
 * Run after `tsc -b`.
 */
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const MARKER = '// GENERATED by scripts/bundle-hooks.cjs';

/** [entry (tsc output), bundle (shipped single file)] */
const TARGETS = [
  ['packages/adapters/claude-code/dist/hook.js', 'packages/adapters/claude-code/dist/hook.js'],
  ['packages/adapters/codex/dist/hook.js', 'packages/adapters/codex/dist/hook.js'],
  ['packages/adapters/opencode/dist/plugin.js', 'packages/adapters/opencode/dist/herdr-gsd-core.js'],
];

const REL_REQUIRE = /require\(\s*"\.\/([A-Za-z0-9_.\-/]+?)(?:\.js)?"\s*\)/g;

function rewrite(code) {
  return code.replace(REL_REQUIRE, (_m, dep) => `__herdrRequire(${JSON.stringify(dep)})`);
}

function collectDeps(dir, code, seen, order) {
  for (const m of code.matchAll(REL_REQUIRE)) {
    const name = m[1];
    if (seen.has(name)) continue;
    seen.add(name);
    const depCode = fs.readFileSync(path.join(dir, `${name}.js`), 'utf8');
    collectDeps(dir, depCode, seen, order);
    order.push({ name, code: depCode });
  }
}

function bundle(entryRel, outRel) {
  const entry = path.join(root, entryRel);
  const out = path.join(root, outRel);
  if (!fs.existsSync(entry)) {
    process.stderr.write(`bundle-hooks: missing ${entryRel} (run tsc -b first)\n`);
    process.exitCode = 1;
    return;
  }

  // Preserve the raw tsc output when the bundle replaces its own entry file.
  let entrySource = entry;
  if (entry === out) {
    const dir = path.dirname(entry);
    entrySource = path.join(dir, `.${path.basename(entry, '.js')}.entry.js`);
    const current = fs.readFileSync(entry, 'utf8');
    if (!current.startsWith(MARKER)) fs.writeFileSync(entrySource, current);
    else if (!fs.existsSync(entrySource)) {
      process.stderr.write(`bundle-hooks: ${entryRel} is already bundled and the raw entry is gone — run \`npm run clean\`\n`);
      process.exitCode = 1;
      return;
    }
  }

  const dir = path.dirname(entry);
  const entryCode = fs.readFileSync(entrySource, 'utf8');
  const order = [];
  collectDeps(dir, entryCode, new Set(), order);

  const parts = [
    MARKER,
    `// Single-file CommonJS bundle of ${entryRel} (spec §12.5): Node builtins only.`,
    '"use strict";',
    'var __herdrMods = {}, __herdrCache = {};',
    'function __herdrRequire(n) {',
    '  if (__herdrCache[n]) return __herdrCache[n].exports;',
    '  var m = __herdrCache[n] = { exports: {} };',
    '  __herdrMods[n](m, m.exports, require);',
    '  return m.exports;',
    '}',
  ];
  for (const { name, code } of order) {
    parts.push(`__herdrMods[${JSON.stringify(name)}] = function (module, exports, require) {\n${rewrite(code)}\n};`);
  }
  parts.push('/* --- entry (top level: keeps module/exports/require.main/__dirname real) --- */');
  parts.push(rewrite(entryCode));

  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${parts.join('\n')}\n`);
  process.stdout.write(`bundle-hooks: wrote ${outRel} (${order.length} inlined module${order.length === 1 ? '' : 's'})\n`);
}

for (const [entryRel, outRel] of TARGETS) bundle(entryRel, outRel);
